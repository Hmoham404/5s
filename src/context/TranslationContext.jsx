const TranslationContext = createContext();

function getValueAtPath(source, path) {
  return path.split(".").reduce((value, part) => value?.[part], source);
}

function interpolate(value, params = {}) {
  return value.replace(/\{(\w+)\}/g, (_, key) => `${params[key] ?? ""}`);
}

export function TranslationProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem(LANGUAGE_STORAGE_KEY) || "fr");

  useEffect(() => {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }, [language]);

  useEffect(() => {
    const locale = languageOptions.find((item) => item.code === language)?.locale || "fr-FR";
    document.documentElement.lang = locale;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const resolveTranslation = (path) =>
    getValueAtPath(translations[language], path) ?? getValueAtPath(translations.fr, path);

  const t = (path, params) => {
    const value = resolveTranslation(path);
    if (typeof value === "function") {
      return value(params);
    }
    if (typeof value === "string") {
      return interpolate(value, params);
    }
    return value ?? path;
  };

  const getZoneName = (zoneOrId, fallback = "") => {
    const id = typeof zoneOrId === "string" ? zoneOrId : zoneOrId?.id;
    const value = zoneNames[language]?.[id] ?? zoneNames.fr[id];
    if (value) return value;
    if (typeof zoneOrId === "object" && zoneOrId?.name) return zoneOrId.name;
    return fallback || id || "";
  };

  const getQuestionText = (questionId, fallback = "") =>
    questionTranslations[language]?.[questionId] ??
    questionTranslations.fr[questionId] ??
    fallback;

  const getStatusLabel = (status) => {
    const key = statusKeyMap[status];
    return key ? t(`statuses.${key}`) : status;
  };

  const getPriorityLabel = (priority) => {
    const key = priorityKeyMap[priority];
    return key ? t(`priorities.${key}`) : priority;
  };

  const getPillarKey = (value) => pillarKeyMap[value] || value;

  const getPillarLabel = (value, variant = "short") => {
    const key = getPillarKey(value);
    return t(`pillars.${key}.${variant}`);
  };

  const getMonthLabel = (month) => {
    const index = typeof month === "number" ? month : monthAliases[month];
    if (index === undefined) return month;
    return t("calendar.months")[index];
  };

  const getDayLabels = () => t("calendar.days");

  const formatDate = (dateString) => {
    if (!dateString) return "";
    const date = new Date(dateString);
    if (Number.isNaN(date.getTime())) return dateString;
    const locale = languageOptions.find((item) => item.code === language)?.locale || "fr-FR";
    return new Intl.DateTimeFormat(locale, {
      year: "numeric",
      month: "short",
      day: "numeric",
    }).format(date);
  };

  return (
    <TranslationContext.Provider
      value={{
        language,
        setLanguage,
        languages: languageOptions,
        dir: language === "ar" ? "rtl" : "ltr",
        t,
        getZoneName,
        getQuestionText,
        getStatusLabel,
        getPriorityLabel,
        getPillarLabel,
        getMonthLabel,
        getDayLabels,
        formatDate,
      }}
    >
      {children}
    </TranslationContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(TranslationContext);
  if (!context) {
    throw new Error("useTranslation must be used within a TranslationProvider");
  }
  return context;
}
